#!/usr/bin/env python3
"""Run the student tests for Assignment 4 and write a report for ANALYSIS.md.

Usage (from the repository root):
    python tests/student/run_student_tests.py
    python tests/student/run_student_tests.py --only lcs,merge
    python tests/student/run_student_tests.py --main Python/source/main.py --no-mixed

What it does
  1. Loads the hand-written fixtures from tests/student/cases.json.
  2. Generates random small cases (checked against independent oracles), boundary cases and
     maximum-size stress cases. Everything is seeded, so every run is identical.
  3. Runs every command in a FRESH process (like the official grader: one task per process).
  4. Runs all cases mixed together, twice, in ONE process to catch state that is not reset.
  5. Validates every answer with tests/student/oracles.py (alternative optima are accepted).
  6. Writes tests/student/results/student_test_results.md (a table with the five columns of
     ANALYSIS.md "Own tests") and student_test_results.json. Exit code is 1 on any failure.

Only real runs are reported. Nothing in the report is typed by hand.
"""
