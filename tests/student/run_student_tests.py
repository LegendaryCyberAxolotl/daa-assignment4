# ----------------------------------------------------------------- execution
def run_process(main_path, requests, timeout):
    payload = "".join(json.dumps(request, separators=(",", ":")) + "\n" for request in requests)
    started = time.perf_counter()
    try:
        process = subprocess.run([sys.executable, str(main_path)], input=payload.encode("utf-8"),
                                 capture_output=True, timeout=timeout)
    except subprocess.TimeoutExpired:
        return None, f"timeout after {timeout}s", time.perf_counter() - started
    elapsed = time.perf_counter() - started
    lines = process.stdout.decode("utf-8", "replace").splitlines()
    problem = ""
    if process.returncode != 0:
        problem = f"process exited with code {process.returncode}: " + process.stderr.decode("utf-8", "replace").strip()[-300:]
    elif len(lines) != len(requests):
        problem = f"expected {len(requests)} result lines, got {len(lines)}"
    outputs = []
    if not problem:
        for line_number, line in enumerate(lines):
            try:
                value = json.loads(line)
                if not isinstance(value, dict):
                    raise ValueError("not an object")
                outputs.append(value)
            except ValueError as error:
                problem = f"result line {line_number + 1} is not a JSON object ({error})"
                break
    return (None if problem else outputs), problem, elapsed


def short(value, limit=70):
    text = json.dumps(value, ensure_ascii=False, separators=(",", ":")) if not isinstance(value, str) else value
    return text if len(text) <= limit else text[:limit - 3] + "..."


def exact_mismatch(expected, output):
    for field_name, value in expected.items():
        if field_name not in output or output[field_name] != value or type(output[field_name]) is not type(value):
            return f"field '{field_name}' differs from the expected value"
    return ""


def validate(command, case, output, cache):
    key = (oracles.FAMILY.get(command, command), case.name)
    try:
        ok, summary, detail = oracles.VALIDATORS[command](case.request, output, cache, key)
        if ok and case.expected:
            detail = exact_mismatch(case.expected, output)
            ok = not detail
    except Exception as error:  # a malformed answer must fail the test, not crash the runner
        ok, summary, detail = False, "", f"validator error {type(error).__name__}: {error}"
    return ok, summary, detail


@dataclass
class Row:
    command: str
    source: str
    expected: str
    actual: str
    checks: str
    ok: bool
    detail: str = ""
    count: int = 1
    passed: int = 1
    extra: dict = field(default_factory=dict)


def expand(cases, commands_filter):
    items = []
    for case in cases:
        for command in case.commands:
            if commands_filter is None or command in commands_filter:
                request = dict(case.request)
                request["task"] = command
                items.append((case, command, request))
    return items


def build_rows(items, results):
    """results[(case.name, command)] = (ok, summary, detail, output_or_None). One row per case, one per random group."""
    rows, group_rows = [], {}
    seen = {}
    for case, _, _ in items:
        seen.setdefault(case.name, case)
    for case in seen.values():
        commands = [c for c in case.commands if (case.name, c) in results]
        per_command = [results[(case.name, c)] for c in commands]
        ok = all(item[0] for item in per_command)
        failure_detail = "; ".join(f"{c}: {r[2]}" for c, r in zip(commands, per_command) if not r[0])
        if case.group:
            row = group_rows.get(case.group)
            if row is None:
                row = Row("/".join(case.commands), f"generated by run_student_tests.py (seed {SEED})",
                          "every case matches the independent oracle", "", case.group, True, count=0, passed=0)
                group_rows[case.group] = row
                rows.append(row)
            row.count += 1
            row.passed += 1 if ok else 0
            row.ok = row.ok and ok
            if not ok and len(row.detail) < 400:
                row.detail += f"[{case.name}: {failure_detail}] "
            continue
        first = per_command[0]
        if case.expected:
            expected_text = "exact " + short(case.expected, 60)
        else:
            expected_text = first[1]
        if first[3] is None:
            actual = "no result: " + first[2]
        else:
            actual = short(first[3])
            if len(per_command) > 1 and ok:
                actual += "  (identical correct answers from " + "/".join(commands) + ")"
        rows.append(Row("/".join(case.commands), case.source, expected_text, actual, case.checks, ok,
                        "" if ok else failure_detail))
    for row in group_rows.values():
        row.actual = f"{row.passed}/{row.count} passed" + ("" if row.ok else "  FAILED " + row.detail)
        row.checks = row.checks + "; catches off-by-one, empty-input and tie-handling defects"
    return rows


def detect_environment():
    return {
        "python": sys.version.split()[0] + " (" + platform.python_implementation() + ")",
        "platform": platform.platform(),
        "machine": platform.machine(),
        "date": datetime.now().strftime("%Y-%m-%d %H:%M:%S"),
    }


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def write_reports(rows, environment, batch_log, args, total_seconds):
    RESULT_DIR.mkdir(exist_ok=True)
    passed = sum(1 for row in rows if row.ok)
    lines = [
        "# Student test results (generated, do not edit)",
        "",
        f"- Date: {environment['date']}",
        f"- Python: {environment['python']}; OS: {environment['platform']}",
        f"- Command: `python tests/student/run_student_tests.py" + (f" --only {args.only}" if args.only else "") + "`",
        f"- Solution under test: `{Path(args.main).as_posix()}` (each command in a fresh process, then one mixed process, two passes)",
        f"- Seed for generated cases: {SEED}",
        f"- Result: **{passed}/{len(rows)} table rows passed**; total wall time {total_seconds:.1f} s",
        "",
        "## Batches (one JSON Lines process per row)",
        "",
        "|Batch|Requests|Wall time (s)|Status|",
        "|---|---:|---:|---|",
    ]
    for name, count, seconds, problem in batch_log:
        lines.append(f"|{cell(name)}|{count}|{seconds:.2f}|{'OK' if not problem else cell(problem)}|")
    lines += ["", "## Own tests", "",
              "|Command|Input or fixture path|Expected result|Actual result / log|What it checks|Status|",
              "|---|---|---|---|---|---|"]
    for row in rows:
        lines.append(f"|{cell(row.command)}|{cell(row.source)}|{cell(row.expected)}|{cell(row.actual)}|{cell(row.checks)}|{'PASS' if row.ok else 'FAIL'}|")
    failures = [row for row in rows if not row.ok]
    if failures:
        lines += ["", "## Failures", ""]
        for row in failures:
            lines.append(f"- `{row.source}` ({row.command}): {row.detail or row.actual}")
    (RESULT_DIR / "student_test_results.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (RESULT_DIR / "student_test_results.json").write_text(json.dumps({
        "environment": environment, "seed": SEED, "passed_rows": passed, "total_rows": len(rows),
        "batches": [{"name": n, "requests": c, "seconds": round(s, 3), "problem": p} for n, c, s, p in batch_log],
        "rows": [{"command": r.command, "source": r.source, "expected": r.expected, "actual": r.actual,
                  "checks": r.checks, "ok": r.ok, "detail": r.detail} for r in rows],
    }, indent=1, ensure_ascii=False), encoding="utf-8")


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--main", default=str(ROOT / "Python" / "source" / "main.py"), help="entry point of the solution")
    parser.add_argument("--only", default="", help="comma-separated commands, e.g. lcs,kmp")
    parser.add_argument("--no-mixed", action="store_true", help="skip the mixed single-process batches")
    parser.add_argument("--timeout", type=int, default=120, help="seconds per process (official limit per batch: 20)")
    args = parser.parse_args()
    commands_filter = None
    if args.only:
        commands_filter = set(args.only.split(","))
        unknown = commands_filter - set(ALL_COMMANDS)
        if unknown:
            parser.error("unknown commands: " + ", ".join(sorted(unknown)))

    started = time.perf_counter()
    cases = load_fixtures() + generated_cases()
    items = expand(cases, commands_filter)
    cache, results, batch_log = {}, {}, []
    environment = detect_environment()
    print(f"{len(cases)} cases, {len(items)} requests; solution: {args.main}")

    # 1. fresh process per command
    for command in ALL_COMMANDS:
        batch = [item for item in items if item[1] == command]
        if not batch:
            continue
        outputs, problem, seconds = run_process(args.main, [request for _, _, request in batch], args.timeout)
        batch_log.append((f"fresh process: {command}", len(batch), seconds, problem))
        for index, (case, _, _) in enumerate(batch):
            if outputs is None:
                results[(case.name, command)] = (False, "", f"batch failed: {problem}", None)
            else:
                ok, summary, detail = validate(command, case, outputs[index], cache)
                results[(case.name, command)] = (ok, summary, detail, outputs[index])
        flag = "ok" if not problem else "PROBLEM: " + problem
        print(f"  fresh {command:<7} {len(batch):>5} requests  {seconds:6.2f}s  {flag}" + ("  (over the official 20 s)" if seconds > 20 else ""))

    rows = build_rows(items, results)

    # 2. mixed batches in a single process
    if not args.no_mixed and items:
        rng = random.Random(f"{SEED}-mixed")
        first_pass = items[:]
        rng.shuffle(first_pass)
        second_pass = items[:]
        rng.shuffle(second_pass)
        sequence = first_pass + second_pass
        outputs, problem, seconds = run_process(args.main, [request for _, _, request in sequence], args.timeout)
        batch_log.append(("mixed process, two shuffled passes", len(sequence), seconds, problem))
        failures = []
        if outputs is None:
            failures.append(f"batch failed: {problem}")
        else:
            for index, (case, command, _) in enumerate(sequence):
                ok, _, detail = validate(command, case, outputs[index], cache)
                if not ok:
                    failures.append(f"pass {1 if index < len(items) else 2} {case.name} [{command}]: {detail}")
        rows.append(Row("all", "generated by run_student_tests.py (all cases shuffled, sent twice to one process)",
                        "every answer valid in both passes; no state leaks between different tasks or repeated requests",
                        f"{len(sequence) - len(failures) if outputs is not None else 0}/{len(sequence)} answers valid"
                        + ("" if not failures else "  FIRST FAILURES: " + " | ".join(failures[:3])),
                        "Stale state between requests, wrong task dispatch, crashes after earlier requests",
                        not failures, "; ".join(failures[:5])))
        print(f"  mixed process {len(sequence):>5} requests  {seconds:6.2f}s  " + ("ok" if not failures else f"{len(failures)} FAILURES"))

    total_seconds = time.perf_counter() - started
    write_reports(rows, environment, batch_log, args, total_seconds)
    passed = sum(1 for row in rows if row.ok)
    for row in rows:
        if not row.ok:
            print(f"FAIL {row.command} {row.source}\n     {row.detail or row.actual}")
    print(f"\n{passed}/{len(rows)} rows passed in {total_seconds:.1f}s. Report: {RESULT_DIR.relative_to(ROOT).as_posix()}/student_test_results.md")
    return 0 if passed == len(rows) else 1


